#!/usr/bin/env python3
"""
Put the real flood hazard level of every barangay into static/data/barangays.geojson (+ barangays.js).

Source: static/data/qc-flood-hazard.geojson, built by scripts/build_qc_flood_hazard.js from the
UP DREAM / Phil-LiDAR 1 "City of Quezon 100 Year Flood Hazard Map (2016)" (481.2 mm rainfall scenario),
downloaded from LiPAD (scripts/source/wfsrequest.txt).

These levels are the agent's H input (photo check and area risk), the Flood areas page, the report
page's hazard hint and the server's area rain check (jobs.py). How the map's classes become the
agent's levels:

    high             -> high
    moderate         -> medium
    low              -> low
    below-threshold  -> low   (some mapped flood area, but under the 20% share: never treated as safe)
    unknown          -> low   (too little of the barangay is covered by the data: never treated as safe)

Usage (from the flood-detection folder):  python scripts/apply_qc_hazard.py
Run it again whenever qc-flood-hazard.geojson is rebuilt.
"""
import json
import pathlib
import sys
from collections import Counter

DATA = pathlib.Path(__file__).resolve().parent.parent / "static" / "data"
LEVEL = {"high": "high", "moderate": "medium", "low": "low", "below-threshold": "low", "unknown": "low"}
SOURCE = "UP DREAM / Phil-LiDAR 1, City of Quezon 100 Year Flood Hazard Map (2016)"


def main():
    qc = json.loads((DATA / "qc-flood-hazard.geojson").read_text(encoding="utf-8"))
    risk = {f["properties"]["name"]: f["properties"].get("risk") for f in qc["features"]}
    brgy = json.loads((DATA / "barangays.geojson").read_text(encoding="utf-8"))

    missing = [f["properties"]["name"] for f in brgy["features"] if f["properties"]["name"] not in risk]
    unknown = sorted({r for r in risk.values() if r not in LEVEL})
    if missing or unknown:
        sys.exit("Stopped: barangays without a hazard level %s, unknown classes %s" % (missing, unknown))

    for f in brgy["features"]:
        p = f["properties"]
        p["hazard"] = LEVEL[risk[p["name"]]]
        p["hazardClass"] = risk[p["name"]]          # the map's own class, for anyone checking
    brgy["_about"] = ("Quezon City barangays. Hazard level per barangay from the %s, 481.2 mm rainfall scenario "
                      "(see scripts/apply_qc_hazard.py for how its classes map to high / medium / low)." % SOURCE)

    text = json.dumps(brgy, ensure_ascii=False, separators=(",", ":"))
    (DATA / "barangays.geojson").write_text(text, encoding="utf-8")
    (DATA / "barangays.js").write_text("/* GENERATED by scripts/build_barangays.py and scripts/apply_qc_hazard.py */\n"
                                       "window.FDA_BARANGAYS = " + text + ";\n", encoding="utf-8")
    print("Hazard levels written for %d barangays: %s" % (len(brgy["features"]),
          dict(Counter(f["properties"]["hazard"] for f in brgy["features"]))))


if __name__ == "__main__":
    main()
